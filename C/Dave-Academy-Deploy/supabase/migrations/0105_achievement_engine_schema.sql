create or replace function public.bump_student_metric(p_student_id bigint, p_metric_key text, p_delta numeric)
returns void
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  insert into public.student_metric_snapshots (student_id, metric_key, value, updated_at)
  values (p_student_id, p_metric_key, p_delta, now())
  on conflict (student_id, metric_key)
  do update set value = public.student_metric_snapshots.value + excluded.value, updated_at = now();
end;
$function$;

revoke execute on function public.bump_student_metric(bigint, text, numeric) from public;
grant execute on function public.bump_student_metric(bigint, text, numeric) to authenticated;

create or replace function public._evaluate_achievements_internal(p_student_id bigint)
returns void
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_level text;
  v_points numeric;
  r record;
  v_qualifies boolean;
  v_inserted integer;
begin
  select level, points into v_level, v_points from public.students where id = p_student_id;
  if v_level is null then
    return;
  end if;

  for r in
    select d.* from public.achievement_definitions d
    where d.active
      and d.trigger_type in ('immediate_event', 'threshold')
      and not exists (
        select 1 from public.student_achievements sa
        where sa.student_id = p_student_id and sa.achievement_id = d.id
      )
  loop
    if r.rule_config->>'metric' = 'total_points' then
      v_qualifies := v_points >= (r.rule_config->>'value')::numeric;
    else
      v_qualifies := exists (
        select 1 from public.student_metric_snapshots m
        where m.student_id = p_student_id
          and m.metric_key = r.rule_config->>'metric'
          and m.value >= (r.rule_config->>'value')::numeric
      );
    end if;

    if not v_qualifies then
      continue;
    end if;

    insert into public.student_achievements (student_id, achievement_id)
    values (p_student_id, r.id)
    on conflict (student_id, achievement_id) do nothing;
    get diagnostics v_inserted = row_count;

    -- Point-award block intentionally removed (owner request, 2026-08-15):
    -- badges still unlock above, but no point_transactions row is
    -- created for them while automatic point awards are paused.
  end loop;
end;
$function$;

create or replace function public.evaluate_achievements(p_student_id bigint)
returns void
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_level text;
  v_authorized_caller boolean;
begin
  select level into v_level from public.students where id = p_student_id;
  if v_level is null then
    return;
  end if;

  v_authorized_caller := public.is_own_student(p_student_id)
    or is_admin()
    or (is_teacher() and exists (
      select 1 from public.teacher_group_assignments tga
      where tga.teacher_id = auth.uid() and tga.level = v_level
    ));

  if not v_authorized_caller then
    return;
  end if;

  perform public._evaluate_achievements_internal(p_student_id);
end;
$function$;

revoke execute on function public.evaluate_achievements(bigint) from public;
grant execute on function public.evaluate_achievements(bigint) to authenticated;
