drop policy if exists lesson_vocabulary_admin_all on public.lesson_vocabulary;
create policy lesson_vocabulary_admin_all on public.lesson_vocabulary for all
  using (is_admin()) with check (is_admin());

drop policy if exists lesson_vocabulary_teacher_all on public.lesson_vocabulary;
create policy lesson_vocabulary_teacher_all on public.lesson_vocabulary for all
  using (is_teacher()) with check (is_teacher());

-- A student may read an active word only for a lesson whose level matches
-- their own (or the lesson has no level restriction) - identical scoping
-- rule to the lesson-pdfs storage policy in 0032, applied here to the row
-- itself instead of a storage path.
drop policy if exists lesson_vocabulary_student_read on public.lesson_vocabulary;
create policy lesson_vocabulary_student_read on public.lesson_vocabulary for select
  using (
    is_active
    and exists (
      select 1
      from public.lessons l
      join public.students s on s.profile_id = auth.uid()
      where l.id = lesson_vocabulary.lesson_id
        and (l.level is null or l.level = s.level)
    )
  );

