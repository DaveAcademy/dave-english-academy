-- Vocabulary Learning System, Phase 1: the data foundation.
--
-- Vocabulary is owned by lessons (Lesson -> Vocabulary), not a standalone
-- module - lesson_vocabulary.lesson_id is the only thing that scopes a
-- word to anything. id is a UUID, deliberately not the bigint identity
-- pattern used elsewhere in this schema: every future feature (favorites,
-- flashcards, quizzes, AI review, analytics) must reference a word by this
-- id, never by its english text, so a later typo fix/translation edit
-- never breaks anything pointing at it.
--
-- Teacher RLS intentionally matches the existing lesson-resource
-- precedent (lesson-pdfs, 0032): any is_teacher() can manage vocabulary
-- for any lesson, same as any teacher can already attach/replace a
-- lesson's PDF. There is no teacher-lesson ownership concept anywhere in
-- this schema to scope against - introducing one here would be new,
-- undocumented restriction logic invented for this feature alone. If
-- real teacher-lesson assignment is added later, this can be tightened
-- to match without a data model change (id stays the same).

create table if not exists public.lesson_vocabulary (
  id uuid primary key default gen_random_uuid(),
  lesson_id bigint not null references public.lessons (id) on delete cascade,
  english text not null,
  uzbek text not null,
  example text,
  pronunciation text,
  image_path text,
  image_name text,
  display_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists lesson_vocabulary_lesson_id_idx on public.lesson_vocabulary (lesson_id);
create index if not exists lesson_vocabulary_display_order_idx on public.lesson_vocabulary (display_order);

-- Kept separate from lesson_vocabulary itself, per design: a student's
-- favorites are their own data, not an attribute of the word.
create table if not exists public.student_vocabulary_favorites (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students (id) on delete cascade,
  vocabulary_id uuid not null references public.lesson_vocabulary (id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (student_id, vocabulary_id)
);

create index if not exists student_vocabulary_favorites_student_id_idx on public.student_vocabulary_favorites (student_id);
create index if not exists student_vocabulary_favorites_vocabulary_id_idx on public.student_vocabulary_favorites (vocabulary_id);

alter table public.lesson_vocabulary enable row level security;
alter table public.student_vocabulary_favorites enable row level security;

-- updated_at is app-relevant audit data, not just a timestamp - keep it
-- accurate on every UPDATE without every caller having to remember to set
-- it (mirrors the plain "set explicitly in the payload" approach used
-- elsewhere in this schema, but as a trigger since teacher CRUD here does
-- partial-field updates from a shared form).
create or replace function public.set_lesson_vocabulary_updated_at()
returns trigger
language plpgsql
set search_path = 'public'
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists lesson_vocabulary_set_updated_at on public.lesson_vocabulary;
create trigger lesson_vocabulary_set_updated_at
  before update on public.lesson_vocabulary
  for each row execute function public.set_lesson_vocabulary_updated_at();

