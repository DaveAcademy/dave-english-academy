-- ---------- storage: optional per-word image, same private 'attachments'
-- bucket as lesson-pdfs, under 'vocabulary-images/{lesson_id}/{filename}'.
-- Mirrors 0032's storage_lesson_id() exactly but for this folder name -
-- kept as a separate function (rather than parameterizing the folder)
-- because storage_lesson_id() is immutable and already relied upon
-- as-is by the lesson-pdfs branch of attachments_read/insert/update.

create or replace function public.storage_vocabulary_lesson_id(p_name text)
returns bigint
language sql
immutable
set search_path = 'public'
as $$
  select case
    when (storage.foldername(p_name))[1] = 'vocabulary-images'
     and (storage.foldername(p_name))[2] ~ '^[0-9]+$'
    then ((storage.foldername(p_name))[2])::bigint
    else null
  end;
$$;

drop policy if exists attachments_read on storage.objects;
create policy attachments_read on storage.objects for select
  using (
    bucket_id = 'attachments'
    and auth.uid() is not null
    and (
      is_admin()
      or is_teacher()
      or (
        (storage.foldername(name))[1] is distinct from 'exam-answers'
        and (storage.foldername(name))[1] is distinct from 'lesson-pdfs'
        and (storage.foldername(name))[1] is distinct from 'vocabulary-images'
      )
      or exists (
        select 1
        from public.exam_scores es
        join public.students s on s.id = es.student_id
        where s.profile_id = auth.uid()
          and es.answer_file_url = name
      )
      or (
        public.storage_lesson_id(name) is not null
        and exists (
          select 1
          from public.lessons l
          join public.students s on s.profile_id = auth.uid()
          where l.id = public.storage_lesson_id(name)
            and (l.level is null or l.level = s.level)
        )
      )
      -- vocabulary-images: same level-scoped rule as lesson-pdfs above.
      or (
        public.storage_vocabulary_lesson_id(name) is not null
        and exists (
          select 1
          from public.lessons l
          join public.students s on s.profile_id = auth.uid()
          where l.id = public.storage_vocabulary_lesson_id(name)
            and (l.level is null or l.level = s.level)
        )
      )
    )
  );

drop policy if exists attachments_insert on storage.objects;
create policy attachments_insert on storage.objects for insert
  with check (
    bucket_id = 'attachments'
    and auth.uid() is not null
    and (
      case (storage.foldername(name))[1]
        when 'exams' then is_admin() or is_teacher()
        when 'certificate-template' then is_admin()
        when 'lesson-pdfs' then is_admin() or is_teacher()
        when 'vocabulary-images' then is_admin() or is_teacher()
        else true
      end
    )
  );

drop policy if exists attachments_update on storage.objects;
create policy attachments_update on storage.objects for update
  using (
    bucket_id = 'attachments'
    and auth.uid() is not null
    and (
      case (storage.foldername(name))[1]
        when 'exams' then is_admin() or is_teacher()
        when 'certificate-template' then is_admin()
        when 'lesson-pdfs' then is_admin() or is_teacher()
        when 'vocabulary-images' then is_admin() or is_teacher()
        else true
      end
    )
  );

