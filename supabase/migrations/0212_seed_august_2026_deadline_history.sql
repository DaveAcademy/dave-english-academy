-- Date of batch operation: around August 2026 (administrator statement)

-- First, ensure the history table exists (idempotent with 0210)
create table if not exists public.student_payment_deadline_history (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.students (id) on delete cascade,
  old_deadline integer not null check (old_deadline between 1 and 31),
  new_deadline integer not null check (new_deadline between 1 and 31),
  effective_date timestamptz not null default now(),
  changed_by uuid references public.profiles (id),
  created_at timestamptz not null default now()
);

create index if not exists student_payment_deadline_history_student_effective_idx
  on public.student_payment_deadline_history (student_id, effective_date);

alter table public.student_payment_deadline_history enable row level security;

drop policy if exists student_payment_deadline_history_admin_all on public.student_payment_deadline_history;
create policy student_payment_deadline_history_admin_all on public.student_payment_deadline_history
  for all using (is_admin()) with check (is_admin());

drop policy if exists student_payment_deadline_history_self_read on public.student_payment_deadline_history;
create policy student_payment_deadline_history_self_read on public.student_payment_deadline_history
  for select using (public.is_own_student(student_payment_deadline_history.student_id));

drop policy if exists student_payment_deadline_history_teacher_read on public.student_payment_deadline_history;
create policy student_payment_deadline_history_teacher_read on public.student_payment_deadline_history
  for select using (
    exists (
      select 1 from public.students s
      where s.id = student_payment_deadline_history.student_id
        and s.group_name is not null
        and exists (
          select 1 from public.teacher_group_assignments tga
          where tga.teacher_id = auth.uid()
            and tga.level = s.level
        )
    )
  );

