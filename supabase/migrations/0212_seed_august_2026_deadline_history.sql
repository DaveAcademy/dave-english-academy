-- For all other students, original deadlines are mathematically reconstructed
-- using the confirmed formula with July 2026 (31 days) as the previous month
-- for rollover calculations, consistent with 4 of 5 admin-provided examples.
--
-- Effective date: 2026-08-01 00:00:00+05:00 (Asia/Tashkent)
-- This is the start of "August 2026" per administrator's "around August 2026"
-- statement. Using the month start is conservative: it ensures all August
-- billing periods use the historical (original) deadlines, preserving paid
-- status for all known August/September payments.
