#!/usr/bin/env node
// Generates frozen Test content migrations from
// src/features/onlineTests/data/test{N}.json (single source of truth).
// Items are frozen on insert: ON CONFLICT DO NOTHING so re-applying never
// mutates published questions. Re-run: node scripts/build-online-test1-migration.cjs
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
// test number -> content migration filename (stable, never rename applied files)
const TARGETS = {
  1: 'supabase/migrations/20261018000001_online_test1_content.sql',
  2: 'supabase/migrations/20261018000002_online_test2_content.sql',
  3: 'supabase/migrations/20261018000003_online_test3_content.sql',
  4: 'supabase/migrations/20261018000004_online_test4_content.sql',
  5: 'supabase/migrations/20261018000005_online_test5_content.sql',
  6: 'supabase/migrations/20261018000006_online_test6_content.sql',
  7: 'supabase/migrations/20261018000007_online_test7_content.sql',
  8: 'supabase/migrations/20261018000008_online_test8_content.sql',
};

const lit = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const str = (v) => `'${String(v).replace(/'/g, "''")}'`;

for (const [num, rel] of Object.entries(TARGETS)) {
const src = JSON.parse(fs.readFileSync(path.join(ROOT, `src/features/onlineTests/data/test${num}.json`), 'utf8'));
const lines = [];
lines.push(`-- Online English Tests: Test ${num} frozen content (Lessons ${src.lesson_from}-${src.lesson_to}).`);
lines.push('-- Generated by scripts/build-online-test1-migration.cjs from');
lines.push(`-- src/features/onlineTests/data/test${num}.json. Do not hand-edit;`);
lines.push('-- regenerate instead. Inserts are DO NOTHING on conflict so');
lines.push('-- re-applying never mutates published (frozen) items.');
lines.push('');
lines.push(`insert into public.online_tests (test_number, title, lesson_from, lesson_to, is_published)`);
lines.push(`values (${src.test_number}, ${str(src.title)}, ${src.lesson_from}, ${src.lesson_to}, true)`);
lines.push(`on conflict (test_number) do nothing;`);
lines.push('');
for (const it of src.items) {
  lines.push(`insert into public.online_test_items (test_id, stage, question_type, position, prompt_data, answer_key, points, source_ref)`);
  lines.push(`values ((select id from public.online_tests where test_number = ${src.test_number}), ${str(it.stage)}, ${str(it.qtype)}, ${it.position}, ${lit(it.prompt)}, ${lit(it.key)}, 1, ${str(it.source_ref)})`);
  lines.push(`on conflict (test_id, stage, position) do nothing;`);
  lines.push('');
}
const out = path.join(ROOT, rel);
fs.writeFileSync(out, lines.join('\n'));
const counts = {};
for (const it of src.items) counts[it.stage] = (counts[it.stage] || 0) + 1;
console.log(`wrote ${out}: ${src.items.length} items`, JSON.stringify(counts));
}
